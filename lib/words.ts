export const PRACTICE_PUNCTUATION = [".", ",", "!", "?", ";", ":"] as const

export type PracticePunctuation = (typeof PRACTICE_PUNCTUATION)[number]

export type GeneratePracticeOptions = {
  wordCount?: number
  includePunctuation?: boolean
}

export const PRACTICE_TEST_DURATION_SECONDS = 60
export const PRACTICE_WORDS_BATCH_INTERVAL_MS = 3500
export const PRACTICE_INITIAL_WORD_COUNT = 12
export const PRACTICE_APPEND_WORD_COUNT = 5

function pickRandomWord(): string {
  return PRACTICE_WORDS[Math.floor(Math.random() * PRACTICE_WORDS.length)]
}

function pickRandomPunctuation(): PracticePunctuation {
  return PRACTICE_PUNCTUATION[
    Math.floor(Math.random() * PRACTICE_PUNCTUATION.length)
  ]
}

export function generatePracticePhrase(
  options: GeneratePracticeOptions = {}
): string {
  const { wordCount = 8, includePunctuation = false } = options
  const words = Array.from({ length: wordCount }, pickRandomWord)

  if (!includePunctuation) {
    return words.join(" ")
  }

  return words
    .map((word, index) => {
      const isLast = index === words.length - 1

      if (isLast) {
        const ending = pickRandomPunctuation()
        return ending === "," ? `${word}.` : `${word}${ending}`
      }

      if (Math.random() < 0.25) {
        return `${word},`
      }

      return word
    })
    .join(" ")
}
